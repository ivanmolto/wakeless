// Task 9.1: the observer's view of both rails from real devnet signatures, and what an
// unprivileged reader rebuilds of each. Reads docs/watcher/public-rail.json and
// docs/watcher/wakeless-run.json, fetches every signature through SOLANA_RPC_URL (devnet,
// asserted), writes docs/watcher/observer-<rail>.json and docs/WATCHER.md, and exits
// non-zero naming the signature and the check when a Wakeless signature fails one of the
// four checks. Read methods only; no keypair is loaded.
//
//   pnpm watcher
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  compare,
  createDevnetReader,
  formatFailures,
  observe,
  parseRunFile,
  reconstruct,
  redactSecrets,
  renderComparison,
  renderMarkdownTable,
  renderTrajectory,
  reportToJson,
  trajectoryToJson,
  type ObserverReport,
  type Reconstruction,
  type RunFile,
} from "@wakeless/watcher";
import { loadDotEnv } from "./lib/env.js";

const ROOT = join(import.meta.dirname, "..");
const DOCS = join(ROOT, "docs", "watcher");

interface RailResult {
  readonly run: RunFile;
  readonly report: ObserverReport;
  readonly rebuilt: Reconstruction;
}

async function runRail(file: string, read: ReturnType<typeof createDevnetReader>): Promise<RailResult> {
  const run = parseRunFile(JSON.parse(readFileSync(join(DOCS, file), "utf8")));
  const report = await observe(run, read);
  const transactions = [];
  for (const s of run.signatures) transactions.push(await read(s.signature));
  const rebuilt = reconstruct(transactions);
  writeFileSync(join(DOCS, `observer-${run.rail}.json`), reportToJson(report));
  writeFileSync(join(DOCS, `reconstruct-${run.rail}.json`), trajectoryToJson(rebuilt));
  return { run, report, rebuilt };
}

function section(result: RailResult): string[] {
  const { run, report, rebuilt } = result;
  const comparison = compare(rebuilt, run.actual);
  const lines: string[] = [];
  lines.push(`## ${run.rail === "public" ? "Public rail" : "Wakeless"}: ${run.title}`, "");
  lines.push(`Signatures: ${report.counts.signatures}; on the base layer: ${report.counts.onBaseLayer}; not on the base layer: ${report.counts.notOnBaseLayer}.`);
  if (run.rail === "wakeless") lines.push(`Four checks: ${report.failures.length === 0 ? "every signature passes" : `${report.failures.length} failed`}.`);
  else lines.push("Four checks on the public rail are information: the rail is expected to fail them, and does.");
  lines.push("", "### What the ledger shows, per signature", "", renderMarkdownTable(report), "");
  lines.push("### What an observer rebuilds", "", renderTrajectory(rebuilt), "", "Against the owner's actual trajectory:", "", renderComparison(comparison), "");
  return lines;
}

async function main(): Promise<void> {
  loadDotEnv(ROOT);
  const rpcUrl = process.env.SOLANA_RPC_URL;
  if (!rpcUrl) throw new Error("SOLANA_RPC_URL is not set; copy .env.example to .env");
  const read = createDevnetReader(rpcUrl);
  const publicRail = await runRail("public-rail.json", read);
  const wakeless = await runRail("wakeless-run.json", read);

  const doc: string[] = [];
  doc.push("# Watcher: the observer's view");
  doc.push("");
  doc.push(`Generated by \`pnpm watcher\` on ${new Date().toISOString().slice(0, 10)} from the signatures in \`docs/watcher/public-rail.json\` and \`docs/watcher/wakeless-run.json\`, read from Solana devnet through the RPC with \`getTransaction\` (\`jsonParsed\`). Nothing here comes from a log of the facilitator, the client or a vendor. The four checks (briefing §5) are: 1 no vendor address; 2 no vendor-attributable amount; 3 no Memo instruction; 4 no fee transfer naming the vendor. A transaction the buyer or the escrow made is checked against the vendors; a vendor's own withdrawal names the vendor by construction and is checked against the escrow and the buyer instead. Program ids and token accounts are shortened in the table; signers and recipients are given in full. JSON: \`docs/watcher/observer-*.json\`, \`docs/watcher/reconstruct-*.json\`.`);
  doc.push("");
  doc.push("The privacy claim is against the public ledger. Three operators see inside: the facilitator (vouchers), MagicBlock's enclave (private transfers) and NEAR's private shard (funding origin and route).");
  doc.push("");
  doc.push(...section(publicRail), ...section(wakeless));
  doc.push("## Reproduce", "", "`https://explorer.solana.com/tx/<signature>?cluster=devnet`. Payment-channels program `CHNLxYvVA28MJP9PrFuDXccuoGXAx7jBacfLEkahyGsX`, decoded with the codama IDL in `vendor/payment-channels` (clone of solana-foundation/payment-channels).", "");
  writeFileSync(join(ROOT, "docs", "WATCHER.md"), doc.join("\n"));

  for (const result of [publicRail, wakeless]) {
    const c = compare(result.rebuilt, result.run.actual);
    console.log(`${result.run.rail.padEnd(9)} signatures ${result.report.counts.signatures}, on base layer ${result.report.counts.onBaseLayer}; rebuilt vendors ${c.vendorsRecovered}/${c.vendorsActual}, spend ${(c.spendRecoveredBps / 100).toFixed(2)}%, order ${c.orderRecovered ? "yes" : "no"}`);
  }
  const failures = formatFailures(wakeless.report);
  if (failures.length > 0) {
    for (const line of failures) console.error(line);
    console.error(`FAIL watcher: ${failures.length} check(s) failed on the Wakeless rail`);
    process.exit(1);
  }
  console.log("PASS watcher: every Wakeless signature passes the four checks; docs/WATCHER.md written");
}

main().catch((error: unknown) => {
  console.error(`[watcher] ${redactSecrets(error instanceof Error ? error.message : String(error))}`);
  process.exit(1);
});
